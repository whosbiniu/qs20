const assert = require('node:assert/strict')
require('../public/terminal-indicators.js')
const node = () => ({ value: '', hidden: true, innerHTML: '', listeners: {}, setAttribute(k,v) { this[k] = v }, focus() { this.focused = true }, addEventListener(k, f) { this.listeners[k] = f } })
const button = node(), panel = node(), list = node(), search = node(), active = node(), close = node(), selected = new Set(['tpo'])
TerminalIndicators.attach({ button, panel, list, search, active, close, get: id => selected.has(id), set: (id,v) => v ? selected.add(id) : selected.delete(id) })
assert.match(list.innerHTML, /Volume Profile/)
assert.match(active.innerHTML, /TPO/)
button.listeners.click(); assert.equal(panel.hidden, false)
search.value = 'footprint'; search.listeners.input()
assert.match(list.innerHTML, /Footprint/); assert.doesNotMatch(list.innerHTML, /Volume Profile/)
list.listeners.click({ target: { closest: () => ({ dataset: { indicator: 'footprint' } }) } })
assert.ok(selected.has('footprint'))
assert.match(active.innerHTML, /Footprint/)
active.listeners.click({ target: { closest: () => ({ dataset: { remove: 'footprint' } }) } })
assert.ok(!selected.has('footprint'))
search.value = 'unavailable'; search.listeners.input(); assert.match(list.innerHTML, /Brak/)
close.listeners.click(); assert.equal(panel.hidden, true)
console.log('Indicator library: catalog, search, add, remove, active legend and close OK')
